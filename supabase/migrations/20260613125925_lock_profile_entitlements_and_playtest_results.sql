-- Profiles are creator-readable but entitlement mutations are backend-only.
-- Removing the UPDATE policy entirely avoids security scanners and future grant
-- changes accidentally turning the policy into a plan or credit escalation path.
REVOKE UPDATE ON TABLE public.profiles FROM anon, authenticated;

DROP POLICY IF EXISTS "Creators update own safe profile fields" ON public.profiles;

COMMENT ON TABLE public.profiles IS
'Creator profiles are owner-readable. All profile mutations, including display name, plan, and credits, require a trusted backend service.';

-- Playtest output is immutable evidence generated by trusted test workers.
-- Creators may read their own results through the existing owner-scoped SELECT
-- policy, but cannot forge, alter, or erase test evidence through the Data API.
REVOKE ALL PRIVILEGES ON TABLE public.playtest_results FROM anon, authenticated;
GRANT SELECT ON TABLE public.playtest_results TO authenticated;
GRANT ALL PRIVILEGES ON TABLE public.playtest_results TO service_role;

ALTER TABLE public.playtest_results ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Creators create playtest results" ON public.playtest_results;
DROP POLICY IF EXISTS "Creators update playtest results" ON public.playtest_results;
DROP POLICY IF EXISTS "Creators delete playtest results" ON public.playtest_results;

COMMENT ON TABLE public.playtest_results IS
'Immutable backend-generated test evidence. Authenticated creators have owner-scoped read-only access; only service_role may insert, update, or delete rows.';
